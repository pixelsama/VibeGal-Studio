const catalogs: Record<StudioLocale, StudioMessageCatalog> = {
  "zh-CN": STUDIO_ZH_CN_MESSAGES,
  en: enMessages,
};

export function normalizeStudioLocale(locale: string | null | undefined): StudioLocale {
  if (!locale) return "zh-CN";
  const parsed = LocaleTagSchema.safeParse(locale);
  if (!parsed.success) return "zh-CN";
  return parsed.data.toLowerCase().startsWith("en") ? "en" : "zh-CN";
}

export function resolveStudioLocale(
  preference: StudioLanguagePreference,
  systemLocales: readonly string[] = getSystemLocales(),
): StudioLocale {
  if (preference !== "system") return preference;
  for (const locale of systemLocales) {
    const parsed = LocaleTagSchema.safeParse(locale);
    if (parsed.success && parsed.data.toLowerCase().startsWith("en")) return "en";
    if (parsed.success && parsed.data.toLowerCase().startsWith("zh")) return "zh-CN";
  }
  return "zh-CN";
}

export function formatStudioMessage(template: string, params: MessageParams = {}): string {
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (placeholder, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder
  ));
}

export function resolveCatalogMessage(
  locale: StudioLocale,
  key: StudioMessageKey,
  params: MessageParams = {},
  options: {
    messages?: Partial<Record<StudioLocale, Partial<StudioMessageCatalog>>>;
    strictMissingEnglish?: boolean;
  } = {},
): string {
  const source = options.messages ?? catalogs;
  const message = source[locale]?.[key];
  if (message !== undefined) return formatStudioMessage(message, params);
  if (locale === "en" && (options.strictMissingEnglish ?? import.meta.env.DEV)) {
    throw new Error(`Missing English Studio message: ${key}`);
  }
  return formatStudioMessage(source["zh-CN"]?.[key] ?? STUDIO_ZH_CN_MESSAGES[key], params);
}

function getSystemLocales(): readonly string[] {
  if (typeof navigator === "undefined") return ["zh-CN"];
  return navigator.languages?.length ? navigator.languages : [navigator.language];
}

function subscribeSystemLocale(onChange: () => void): () => void {
  if (typeof window === "undefined") return () => {};
  window.addEventListener("languagechange", onChange);
  return () => window.removeEventListener("languagechange", onChange);
}

function readSystemLocale(): StudioLocale {
  return resolveStudioLocale("system");
}

interface StudioI18nContextValue {
  locale: StudioLocale;
  t: (key: StudioMessageKey, params?: MessageParams) => string;
}

const defaultStudioI18n: StudioI18nContextValue = {
  locale: "zh-CN",
  t: (key, params) => resolveCatalogMessage("zh-CN", key, params),
};

const StudioI18nContext = createContext<StudioI18nContextValue>(defaultStudioI18n);

export function StudioI18nProvider({
  preference,
  children,
}: {
  preference: StudioLanguagePreference;
  children: ReactNode;
}) {
  const systemLocale = useSyncExternalStore<StudioLocale>(
    subscribeSystemLocale,
    readSystemLocale,
    () => readSystemLocale(),
  );
  const locale: StudioLocale = preference === "system" ? systemLocale : preference;
  const value = useMemo<StudioI18nContextValue>(() => ({
    locale,
    t: (key, params) => resolveCatalogMessage(locale, key, params),
  }), [locale]);

  useEffect(() => {
    if (typeof document !== "undefined") document.documentElement.lang = locale;
  }, [locale]);

  return <StudioI18nContext.Provider value={value}>{children}</StudioI18nContext.Provider>;
}

export function useStudioI18n(): StudioI18nContextValue {
  return useContext(StudioI18nContext);
}
